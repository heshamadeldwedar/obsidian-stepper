// Add a name to NAMES and run `npm run icons`.
import fs from 'node:fs';

const NAMES = [
  'server', 'database', 'users', 'user', 'globe', 'zap', 'activity', 'trending-up', 'cpu', 'triangle-alert', 'check', 'x',
  'clock', 'info', 'lightbulb', 'sparkles', 'flag', 'play', 'pause', 'rotate-ccw', 'arrow-left', 'arrow-right', 'maximize-2',
  'shield', 'lock', 'key', 'mail', 'message-square', 'box', 'package', 'layers', 'network', 'gauge', 'hard-drive',
  'smartphone', 'laptop', 'cloud', 'list-ordered', 'git-branch', 'bell', 'search', 'file', 'credit-card', 'shopping-cart',
  'hourglass', 'timer', 'split', 'filter', 'eye', 'bug', 'heart-pulse', 'workflow', 'inbox', 'hash', 'scale', 'route',
  'signpost', 'refresh-cw', 'settings', 'chart-column', 'gift', 'car', 'image', 'video', 'radio', 'boxes', 'braces',
  'shopping-cart', 'chart-line', 'circle-check', 'dollar-sign', 'eye-off', 'file-key', 'git-commit-horizontal', 'id-card',
  'sheet', 'signal', 'siren', 'toggle-left', 'user-check', 'zoom-in', 'lock-keyhole', 'skull', 'scroll', 'flask-conical',
  'plane', 'hotel', 'hammer', 'waves', 'wifi', 'unplug', 'share-2', 'ticket', 'sigma', 'map', 'moon', 'power', 'rocket',
  'waypoints', 'building', 'bot', 'ban', 'merge', 'undo-2', 'clipboard',
];

const lines = NAMES.map(name => {
  const svg = fs.readFileSync(`node_modules/lucide-static/icons/${name}.svg`, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '');
  return `  '${name}': '${inner}',`;
});

fs.writeFileSync('src/icons.js', `// Lucide icons (https://lucide.dev, ISC license). Generated by tools/build-icons.js. Don't edit by hand.
// Each value is the inside of a 24×24 SVG drawn with strokes.
export const ICONS = {
${lines.join('\n')}
};
`);
console.log(`src/icons.js: ${NAMES.length} icons`);
